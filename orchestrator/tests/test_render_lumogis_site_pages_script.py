@pytest.mark.skipif(not _node_available(), reason="node not available")
def test_missing_site_out_fails() -> None:
    env = {
        k: v
        for k, v in __import__("os").environ.items()
        if k not in ("LUMOGIS_SITE_ROOT", "LUMOGIS_RENDER_DISABLE_SIBLING")
    }
    env["LUMOGIS_RENDER_DISABLE_SIBLING"] = "1"
    result = subprocess.run(
        [
            "node",
            str(SCRIPT),
            "--capabilities-md",
            str(FIXTURES / "capabilities-minimal.md"),
            "--changelog-md",
            str(FIXTURES / "changelog-with-unreleased.md"),
            "--shell",
            str(SHELL),
        ],
        cwd=REPO,
        capture_output=True,
        text=True,
        check=False,
        env=env,
    )
    assert result.returncode != 0
