"""Caddy site block for the household's secure address (LUM-331). Pure; no I/O.

The block is written to ``{CADDY_HOME_DIR}/home.caddy`` and imported by the main
Caddyfile (``import /etc/caddy/home.d/*.caddy``). It serves exactly the same app
as the LAN address through the shared ``(lumogis_routes)`` snippet, and lets
Caddy obtain and renew the certificate itself via DNS-01 through the Home DNS
Worker's acme-dns-compatible ``/update`` endpoint.

Every interpolated value is validated first: this text becomes server
configuration, so a value with a brace or newline must never reach it.
"""

from __future__ import annotations

from services.home_dns import validate

LE_STAGING_DIRECTORY = "https://acme-staging-v02.api.letsencrypt.org/directory"


def render(
    household_id: str,
    bearer: str,
    server_url: str,
    *,
    staging: bool = False,
    https_port: int = 443,
) -> str:
    """The household site block; raises ``ValueError`` for any invalid input."""
    if not validate.valid_household_id(household_id):
        raise ValueError("invalid household id")
    if not validate.valid_bearer(bearer):
        raise ValueError("invalid bearer")
    if not validate.valid_server_url(server_url):
        raise ValueError("invalid server url")
    if not isinstance(https_port, int) or not 1 <= https_port <= 65535:
        raise ValueError("invalid https port")
    name = validate.name_for(household_id)

    lines = [
        "# Generated by Lumogis (LUM-331, Secure address). Do not edit: it is",
        "# rewritten when the secure address is turned on, changed or off.",
        f"{name} {{",
        "\ttls {",
        "\t\tdns acmedns {",
        f"\t\t\tusername {household_id}",
        f"\t\t\tpassword {bearer}",
        f"\t\t\tsubdomain {household_id}",
        f"\t\t\tserver_url {server_url}",
        "\t\t}",
    ]
    if staging:
        lines.append(f"\t\tca {LE_STAGING_DIRECTORY}")
    lines += [
        "\t}",
        "\timport lumogis_routes",
        "}",
    ]
    if https_port != 443:
        # Caddy's automatic redirect would send http://{name} to the container's
        # :443, which the host publishes elsewhere.
        lines += [
            f"http://{name} {{",
            f"\tredir https://{name}:{https_port}{{uri}} permanent",
            "}",
        ]
    return "\n".join(lines) + "\n"
